"""save_session works after the server restarts.

Code history lived only in memory, so a restarted MCP server (a deploy,
an idle shutdown, another instance) answered "save this script" in a
session that had run code with "No code has been executed yet"
(2026-10-06 review). Each successful run_code also writes the session's
history to <script_dir>/session_*.py, one marked section per call; a
session's state is now rebuilt from that file when first created.
"""
import json
import os
import shutil
import uuid

import pytest

import geeViz.mcp.server as srv


@pytest.fixture
def restarted_session():
    sid = "test_restart_" + uuid.uuid4().hex[:10]
    folder = os.path.join(srv._BASE_SCRIPT_DIR, sid)
    os.makedirs(folder, exist_ok=True)
    with open(os.path.join(folder, "session_20261006_231000.py"), "w", encoding="utf-8") as fh:
        fh.write(
            "# Auto-generated by geeViz MCP server\n"
            "# Each section below is one run_code call, in order.\n\n"
            "import geeViz.geeView as gv\nee = gv.ee\nMap = gv.Map\n\n"
            "# --- run_code call 1 ---\n"
            "area = ee.Geometry.Point([-111.9, 40.7]).buffer(5000)\n\n"
            "# --- run_code call 2 ---\n"
            "dem = ee.Image('USGS/3DEP/10m')\n"
            "Map.addLayer(dem.clip(area), {}, 'DEM')\n")
    srv._sessions.pop(sid, None)          # as if this process never saw it
    yield sid
    srv._sessions.pop(sid, None)
    shutil.rmtree(folder, ignore_errors=True)


def test_history_is_rebuilt_from_the_saved_script(restarted_session):
    sess = srv._get_session(restarted_session)
    assert len(sess.code_history) == 2
    assert sess.code_history[0].startswith("area = ee.Geometry.Point")
    assert "Map.addLayer(dem.clip(area)" in sess.code_history[1]
    assert len(sess.code_history_meta) == 2
    assert "area" in sess.code_history_meta[0]["names_bound"]


def test_save_session_writes_the_code_instead_of_refusing(restarted_session):
    out = json.loads(srv.save_session(session_id=restarted_session))
    assert "error" not in out, out
    with open(out["script_path"], encoding="utf-8") as fh:
        saved = fh.read()
    assert "ee.Geometry.Point([-111.9, 40.7])" in saved and "USGS/3DEP/10m" in saved


def test_a_session_with_no_saved_script_still_starts_empty():
    sid = "test_restart_" + uuid.uuid4().hex[:10]
    try:
        assert srv._get_session(sid).code_history == []
    finally:
        srv._sessions.pop(sid, None)
